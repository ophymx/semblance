#include "textflag.h"

// func csaNEON(planes *[8][4]uint64, block []uint64)
//
// Four independent carry-save-adder banks: planes for banks 0-1 live in
// the 64-bit lanes of V0..V7, banks 2-3 in V16..V23. Each iteration loads
// four words and runs two interleaved ripple-carry cascades (temporaries
// V8/V10 and V9/V11) so wide arm64 cores can dual-issue them. The final
// carry out of plane 7 is dropped; callers guarantee at most 255 words per
// lane so it is always zero.
TEXT ·csaNEON(SB), NOSPLIT, $0-32
	MOVD planes+0(FP), R0
	MOVD block_base+8(FP), R1
	MOVD block_len+16(FP), R2
	LSR  $2, R2

	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16
	VEOR V16.B16, V16.B16, V16.B16
	VEOR V17.B16, V17.B16, V17.B16
	VEOR V18.B16, V18.B16, V18.B16
	VEOR V19.B16, V19.B16, V19.B16
	VEOR V20.B16, V20.B16, V20.B16
	VEOR V21.B16, V21.B16, V21.B16
	VEOR V22.B16, V22.B16, V22.B16
	VEOR V23.B16, V23.B16, V23.B16

	CBZ R2, done

loop:
	VLD1.P 32(R1), [V8.B16, V9.B16]

	VAND V0.B16, V8.B16, V10.B16
	VAND V16.B16, V9.B16, V11.B16
	VEOR V8.B16, V0.B16, V0.B16
	VEOR V9.B16, V16.B16, V16.B16

	VAND V1.B16, V10.B16, V8.B16
	VAND V17.B16, V11.B16, V9.B16
	VEOR V10.B16, V1.B16, V1.B16
	VEOR V11.B16, V17.B16, V17.B16

	VAND V2.B16, V8.B16, V10.B16
	VAND V18.B16, V9.B16, V11.B16
	VEOR V8.B16, V2.B16, V2.B16
	VEOR V9.B16, V18.B16, V18.B16

	VAND V3.B16, V10.B16, V8.B16
	VAND V19.B16, V11.B16, V9.B16
	VEOR V10.B16, V3.B16, V3.B16
	VEOR V11.B16, V19.B16, V19.B16

	VAND V4.B16, V8.B16, V10.B16
	VAND V20.B16, V9.B16, V11.B16
	VEOR V8.B16, V4.B16, V4.B16
	VEOR V9.B16, V20.B16, V20.B16

	VAND V5.B16, V10.B16, V8.B16
	VAND V21.B16, V11.B16, V9.B16
	VEOR V10.B16, V5.B16, V5.B16
	VEOR V11.B16, V21.B16, V21.B16

	VAND V6.B16, V8.B16, V10.B16
	VAND V22.B16, V9.B16, V11.B16
	VEOR V8.B16, V6.B16, V6.B16
	VEOR V9.B16, V22.B16, V22.B16

	VEOR V10.B16, V7.B16, V7.B16
	VEOR V11.B16, V23.B16, V23.B16

	SUBS $1, R2
	BNE  loop

done:
	VST1.P [V0.B16], 16(R0)
	VST1.P [V16.B16], 16(R0)
	VST1.P [V1.B16], 16(R0)
	VST1.P [V17.B16], 16(R0)
	VST1.P [V2.B16], 16(R0)
	VST1.P [V18.B16], 16(R0)
	VST1.P [V3.B16], 16(R0)
	VST1.P [V19.B16], 16(R0)
	VST1.P [V4.B16], 16(R0)
	VST1.P [V20.B16], 16(R0)
	VST1.P [V5.B16], 16(R0)
	VST1.P [V21.B16], 16(R0)
	VST1.P [V6.B16], 16(R0)
	VST1.P [V22.B16], 16(R0)
	VST1.P [V7.B16], 16(R0)
	VST1.P [V23.B16], 16(R0)
	RET
